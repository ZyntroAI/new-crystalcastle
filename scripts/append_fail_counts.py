#!/usr/bin/env python3
"""
Append CI/CD Fail Counts to PR Descriptions
เพิ่มจำนวนครั้งที่ CI ล้มลงในคำอธิบาย Pull Request
Exit Codes:
  0 = Success
  1 = Missing environment variables
  2 = GitHub API request failed
  3 = No open PRs found
"""

import os
import sys
import json
from datetime import datetime

# ─── Configuration ──────────────────────────────────────────────
GITHUB_TOKEN = os.getenv("GITHUB_TOKEN")
REPO = os.getenv("REPO")  # format: owner/repo
API_VERSION = "2022-11-28"

# ─── Validation ────────────────────────────────────────────────
def validate_env():
    """ตรวจสอบตัวแปรสภาพแวดล้อมครบถ้วน"""
    missing = []
    if not GITHUB_TOKEN:
        missing.append("GITHUB_TOKEN")
    if not REPO:
        missing.append("REPO")
    if missing:
        print(f"❌ Missing environment variables: {', '.join(missing)}", file=sys.stderr)
        sys.exit(1)
    print(f"✅ Config loaded: REPO={REPO}")

# ─── GitHub API Helpers ─────────────────────────────────────────
def github_request(method, path, data=None):
    """เรียก GitHub API พร้อมจัดการข้อผิดพลาด"""
    import urllib.request
    import urllib.error

    url = f"https://api.github.com{path}"
    headers = {
        "Authorization": f"token {GITHUB_TOKEN}",
        "Accept": "application/vnd.github+json",
        "X-GitHub-Api-Version": API_VERSION,
        "User-Agent": "ZyntroAI-CI-Fail-Counter",
    }

    req = urllib.request.Request(url, method=method.upper())
    for k, v in headers.items():
        req.add_header(k, v)

    try:
        if data:
            req.data = json.dumps(data).encode("utf-8")
            req.add_header("Content-Type", "application/json")

        with urllib.request.urlopen(req) as resp:
            return json.loads(resp.read().decode()), resp.status

    except urllib.error.HTTPError as e:
        body = e.read().decode() or "No response body"
        print(f"❌ API Error {e.code}: {body}", file=sys.stderr)
        sys.exit(2)
    except Exception as e:
        print(f"❌ Request failed: {str(e)}", file=sys.stderr)
        sys.exit(2)

# ─── Core Logic ─────────────────────────────────────────────────
def get_open_prs():
    """ดึงรายการ PR ที่เปิดอยู่"""
    print("🔍 Fetching open pull requests...")
    data, _ = github_request("GET", f"/repos/{REPO}/pulls?state=open&per_page=100")
    if not data:
        print("ℹ️ No open PRs found — nothing to do")
        sys.exit(3)
    print(f"✅ Found {len(data)} open PR(s)")
    return data

def get_pr_checks(pr_number):
    """ดึงสถานะการตรวจสอบของ PR นั้น"""
    data, _ = github_request(
        "GET",
        f"/repos/{REPO}/commits/{pr_number['head']['sha']}/check-runs?per_page=100"
    )
    return data.get("check_runs", [])

def count_failures(check_runs):
    """นับจำนวนครั้งที่ล้มแยกตามประเภท"""
    counts = {"total": 0, "failed": 0, "cancelled": 0, "success": 0}
    for run in check_runs:
        conclusion = run.get("conclusion", "").lower()
        counts["total"] += 1
        if conclusion in ("failure", "action_required", "timed_out"):
            counts["failed"] += 1
        elif conclusion == "cancelled":
            counts["cancelled"] += 1
        elif conclusion == "success":
            counts["success"] += 1
    return counts

def build_append_text(pr_number, counts):
    """สร้างข้อความที่จะต่อท้ายคำอธิบาย"""
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S UTC")
    return f"""

---

### 📊 CI/CD Status — Updated {timestamp}

- **Checks:** {counts['total']} ran
- ✅ Passed: {counts['success']}
- ❌ Failed: {counts['failed']}
- ⚠️ Cancelled: {counts['cancelled']}

> Auto-generated by `append_fail_counts.py`
"""

def update_pr_body(pr, append_text):
    """อัปเดตคำอธิบาย PR โดยไม่ซ้ำเนื้อหาเดิม"""
    current = pr.get("body") or ""

    # ถ้ามีข้อความนี้แล้ว → ข้ามไม่ให้ซ้ำ
    if "Auto-generated by `append_fail_counts.py`" in current:
        print(f"⏭️ PR #{pr['number']} — already updated, skipping")
        return

    new_body = current.rstrip() + append_text
    github_request(
        "PATCH",
        f"/repos/{REPO}/pulls/{pr['number']}",
        data={"body": new_body}
    )
    print(f"✅ Updated PR #{pr['number']}: {pr['title'][:50]}...")

# ─── Main ────────────────────────────────────────────────────────
def main():
    validate_env()
    prs = get_open_prs()

    updated = 0
    for pr in prs:
        checks = get_pr_checks(pr)
        counts = count_failures(checks)
        append_text = build_append_text(pr["number"], counts)
        update_pr_body(pr, append_text)
        updated += 1

    print(f"\n🎉 Done — processed {updated} PR(s) successfully")
    sys.exit(0)

if __name__ == "__main__":
    main()
